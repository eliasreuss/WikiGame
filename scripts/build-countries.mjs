// Builds the bundled game data:
//   src/data/countries.json  — sovereign states from Wikidata (QID, name, ISO code, coordinates, enwiki title)
//   src/data/landmask.ts     — a low-res Mercator land grid for the dot-matrix map
// Run with: npm run build:data
import { writeFile, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const OUT_DIR = new URL('../src/data/', import.meta.url);

const SPARQL = `
SELECT ?country ?countryLabel ?type ?iso ?coord ?article ?population WHERE {
  VALUES ?type { wd:Q6256 wd:Q3624078 }
  ?country wdt:P31 ?type;
           wdt:P297 ?iso;
           wdt:P625 ?coord.
  FILTER NOT EXISTS { ?country wdt:P576 ?dissolved. }
  OPTIONAL { ?country wdt:P1082 ?population. }
  ?article schema:about ?country;
           schema:isPartOf <https://en.wikipedia.org/>.
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
}`;

const DISPLAY_NAMES = {
  "People's Republic of China": 'China',
  'Kingdom of the Netherlands': 'Netherlands',
  'The Gambia': 'Gambia',
  'Czech Republic': 'Czechia',
};

async function fetchCountries() {
  const url = `https://query.wikidata.org/sparql?format=json&query=${encodeURIComponent(SPARQL)}`;
  const res = await fetch(url, {
    headers: { 'User-Agent': 'WikiDaily-prototype/0.1 (game prototype; build script)', Accept: 'application/sparql-results+json' },
  });
  if (!res.ok) throw new Error(`SPARQL failed: ${res.status}`);
  const json = await res.json();

  // Some states (Denmark, the Netherlands) have a "country" item and a separate
  // "kingdom" sovereign-state item sharing one ISO code; the "country" item wins.
  const byIso = new Map();
  for (const b of json.results.bindings) {
    const qid = b.country.value.split('/').pop();
    const m = /Point\(([-\d.eE]+) ([-\d.eE]+)\)/.exec(b.coord.value);
    if (!m) continue;
    const iso = b.iso.value.toLowerCase();
    const isCountry = b.type.value.endsWith('/Q6256');
    const population = b.population ? Number(b.population.value) : 0;
    const prev = byIso.get(iso);
    if (prev && (prev.isCountry && !isCountry || (prev.isCountry === isCountry && prev.population >= population))) continue;
    byIso.set(iso, {
      isCountry,
      qid,
      name: DISPLAY_NAMES[b.countryLabel.value] ?? b.countryLabel.value,
      iso2: iso,
      lat: Math.round(Number(m[2]) * 1e4) / 1e4,
      lon: Math.round(Number(m[1]) * 1e4) / 1e4,
      wikiTitle: decodeURIComponent(b.article.value.split('/wiki/').pop()),
      population,
    });
  }

  // Keep the better-known ~150 states so daily pairs stay guessable.
  return [...byIso.values()]
    .sort((a, b) => b.population - a.population)
    .slice(0, 150)
    .map(({ population, isCountry, ...rest }) => rest)
    .sort((a, b) => a.name.localeCompare(b.name));
}

const MAP = { cols: 96, latMin: -56, latMax: 76 };
const merc = (latDeg) => Math.log(Math.tan(Math.PI / 4 + (latDeg * Math.PI) / 360));

async function buildLandmask() {
  const topo = JSON.parse(await readFile(require.resolve('world-atlas/land-50m.json'), 'utf8'));
  const land = feature(topo, topo.objects.land);
  const step = (2 * Math.PI) / MAP.cols;
  const yMax = merc(MAP.latMax);
  const yMin = merc(MAP.latMin);
  const rows = Math.round((yMax - yMin) / step);
  const lines = [];
  for (let r = 0; r < rows; r++) {
    const y = yMax - (r + 0.5) * step;
    const lat = (2 * Math.atan(Math.exp(y)) - Math.PI / 2) * (180 / Math.PI);
    let line = '';
    for (let c = 0; c < MAP.cols; c++) {
      const lon = -180 + (c + 0.5) * (360 / MAP.cols);
      line += geoContains(land, [lon, lat]) ? '1' : '0';
    }
    lines.push(line);
  }
  return { rows, lines };
}

const countries = await fetchCountries();
await writeFile(new URL('countries.json', OUT_DIR), JSON.stringify(countries, null, 1) + '\n');
console.log(`countries.json: ${countries.length} countries`);

const { rows, lines } = await buildLandmask();
const ts = `// Generated by scripts/build-countries.mjs — do not edit by hand.
// Mercator grid, ${MAP.cols} columns x ${rows} rows, latitude ${MAP.latMin} to ${MAP.latMax}.
export const LANDMASK = {
  cols: ${MAP.cols},
  rows: ${rows},
  latMin: ${MAP.latMin},
  latMax: ${MAP.latMax},
  lines: [
${lines.map((l) => `    '${l}',`).join('\n')}
  ],
} as const;
`;
await writeFile(new URL('landmask.ts', OUT_DIR), ts);
console.log(`landmask.ts: ${MAP.cols}x${rows}`);
