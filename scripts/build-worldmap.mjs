// Builds src/data/worldmap.ts: country outlines as SVG paths in a Mercator plane, for the Origin map.
// Names come from src/data/countries.json where a Wikidata country point falls inside the shape.
// Run with: npm run build:map (after build:data, which writes countries.json)
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { geoContains, geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const OUT_DIR = new URL('../src/data/', import.meta.url);

const MAP = { width: 9600, latMin: -56, latMax: 76 };
const merc = (latDeg) => Math.log(Math.tan(Math.PI / 4 + (latDeg * Math.PI) / 360));
const Y_TOP = merc(MAP.latMax);
const Y_SPAN = Y_TOP - merc(MAP.latMin);
const HEIGHT = Math.round((MAP.width * Y_SPAN) / (2 * Math.PI));
// Vertices closer than this (in map units, ~0.08° of longitude) are merged.
const MIN_STEP = 2;

// Natural Earth abbreviates long names; these are shown to players under their pin.
const NAME_FIXES = {
  'Antigua and Barb.': 'Antigua and Barbuda',
  'Br. Indian Ocean Ter.': 'British Indian Ocean Territory',
  'British Virgin Is.': 'British Virgin Islands',
  'Cayman Is.': 'Cayman Islands',
  'Cook Is.': 'Cook Islands',
  eSwatini: 'Eswatini',
  'Faeroe Is.': 'Faroe Islands',
  'Falkland Is.': 'Falkland Islands',
  'Fr. Polynesia': 'French Polynesia',
  'Fr. S. Antarctic Lands': 'French Southern Lands',
  'Heard I. and McDonald Is.': 'Heard and McDonald Islands',
  'Indian Ocean Ter.': 'Australian Indian Ocean Territories',
  'Marshall Is.': 'Marshall Islands',
  'N. Cyprus': 'Northern Cyprus',
  'N. Mariana Is.': 'Northern Mariana Islands',
  'Pitcairn Is.': 'Pitcairn Islands',
  'S. Geo. and the Is.': 'South Georgia',
  'Solomon Is.': 'Solomon Islands',
  'St-Barthélemy': 'Saint Barthélemy',
  'St-Martin': 'Saint Martin',
  'St. Kitts and Nevis': 'Saint Kitts and Nevis',
  'St. Pierre and Miquelon': 'Saint Pierre and Miquelon',
  'St. Vin. and Gren.': 'Saint Vincent and the Grenadines',
  'Turks and Caicos Is.': 'Turks and Caicos Islands',
  'U.S. Virgin Is.': 'U.S. Virgin Islands',
  'W. Sahara': 'Western Sahara',
  'Wallis and Futuna Is.': 'Wallis and Futuna',
};

// d3's Mercator cuts shapes at the antimeridian (Russia, Fiji) and clips to the latitude band,
// matching y = (mercY(latMax) - mercY(lat)) * width / 2π used by the app.
const scale = MAP.width / (2 * Math.PI);
const projection = geoMercator()
  .scale(scale)
  .translate([MAP.width / 2, scale * Y_TOP])
  .clipExtent([
    [0, 0],
    [MAP.width, HEIGHT],
  ])
  .precision(0.5);

/** Collects the projected rings of a feature as relative-integer SVG path data. */
function featurePath(f) {
  const rings = [];
  let ring = [];
  const push = (x, y) => {
    const q = [Math.round(x), Math.round(y)];
    const last = ring[ring.length - 1];
    if (last && Math.abs(q[0] - last[0]) < MIN_STEP && Math.abs(q[1] - last[1]) < MIN_STEP) return;
    ring.push(q);
  };
  geoPath(projection, {
    moveTo(x, y) {
      ring = [];
      push(x, y);
    },
    lineTo: push,
    closePath() {
      if (ring.length >= 3) rings.push(ring);
      ring = [];
    },
    arc() {},
  })(f);
  return rings
    .map((pts) => {
      let d = `M${pts[0][0]} ${pts[0][1]}`;
      for (let i = 1; i < pts.length; i++) d += `l${pts[i][0] - pts[i - 1][0]} ${pts[i][1] - pts[i - 1][1]}`;
      return d + 'z';
    })
    .join('');
}

const topo = JSON.parse(await readFile(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const countries = JSON.parse(await readFile(new URL('countries.json', OUT_DIR), 'utf8'));
const shapes = feature(topo, topo.objects.countries).features;

const out = [];
for (const f of shapes) {
  if (f.properties.name === 'Antarctica') continue;
  const d = featurePath(f);
  if (!d) continue;
  const named = countries.find((c) => geoContains(f, [c.lon, c.lat]));
  out.push({ name: named?.name ?? NAME_FIXES[f.properties.name] ?? f.properties.name, d });
}
out.sort((a, b) => a.name.localeCompare(b.name));

const ts = `// Generated by scripts/build-worldmap.mjs from Natural Earth 1:50m (world-atlas) — do not edit by hand.
// Mercator plane, ${MAP.width} x ${HEIGHT} units, latitude ${MAP.latMin} to ${MAP.latMax}. Paths use relative integer steps.
export type WorldCountry = { name: string; d: string };

export const WORLD = {
  width: ${MAP.width},
  height: ${HEIGHT},
  latMin: ${MAP.latMin},
  latMax: ${MAP.latMax},
  countries: [
${out.map((c) => `    { name: ${JSON.stringify(c.name)}, d: '${c.d}' },`).join('\n')}
  ] as WorldCountry[],
};
`;
await writeFile(new URL('worldmap.ts', OUT_DIR), ts);
console.log(`worldmap.ts: ${out.length} countries, ${(ts.length / 1024).toFixed(0)} KB`);
